"""Export the Scout terminal's data for the sandbox: sandbox/terminal.json.

The sandbox has no backend, so the terminal reads one JSON file. This script builds it from part A's metrics engine
directly (``regista.season.metrics``, ``regista.season.profiles``), not over HTTP, and writes everything the terminal
needs and nothing more:

- the metric catalogue (127 player metrics, 19 team-style metrics) with definitions, rules, sources, units, kinds,
  direction, positions, noisy flags and minimums;
- every league player: the public bio only, minutes, appearances, and every metric's value, count and percentile;
- evidence per metric (the events behind each number, capped at EVIDENCE_CAP items per metric with the true total kept),
  stored once per player as "moments" and referenced by index;
- shots (attacking frame, xG, outcome, body part, minute, clip), the touch heat-map grid, form per match, similar players;
- team style per club and the league table;
- "app": the local app that serves the clip videos (never the live app: it still runs the old league).

The hidden ratings (league.json "attributes": RATINGS, GK_RATINGS, PHYSICAL) never reach the output; the script asserts it.
Synthetic data: invented players and clubs in the Regista League, generated by Regista.

Run from anywhere (the engine's own repo checkout is found from the package):

    PYTHONPATH=/path/to/Regista/src REGISTA_DOTENV= python3 sandbox/tools/export_terminal.py [--app URL] [--out FILE]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import sys
from pathlib import Path
from typing import Any

os.environ.setdefault("REGISTA_DOTENV", "")   # never load .env; nothing here reaches Azure

import regista
from regista.schema import iter_jsonl
from regista.season import league as league_mod
from regista.season.metrics import (CATALOGUE, DEFAULT_COLUMNS, GROUPS, SIMILARITY_TEMPLATE, SOURCES, SYNTHETIC_NOTE,
                                    TEAM_CATALOGUE, SeasonMetrics, load_metrics)
from regista.season.profiles import GRID_X, GRID_Y, load_season
from regista.synth.generator import PITCH_L, PITCH_W

REPO = Path(regista.__file__).resolve().parents[2]
SANDBOX = Path(__file__).resolve().parents[1]
DEFAULT_APP = "http://localhost:8040"
EVIDENCE_CAP = 10        # items per metric per player, the engine API's own default (terminal_api.TABLE_EVIDENCE)
SIMILAR_N = 5
VIDEO_URL = "/api/matches/{match_id}/clips/{clip_id}.mp4"   # the engine's video_url; the app base goes in front

# The hidden ratings' field names, from the engine itself (league.py): none of these may appear as a key in the output.
HIDDEN_KEYS = frozenset({"attributes", *league_mod.RATINGS, *league_mod.GK_RATINGS, *league_mod.PHYSICAL,
                         *league_mod.ATTRIBUTE_KEYS})
BIO = ("age", "height_cm", "preferred_foot", "nationality")   # public bio (date of birth left out: age says enough)


def r(v: float | None, digits: int = 2) -> float | None:
    return None if v is None else round(v, digits)


# ------------------------------------------------------------------------------------------------ catalogue
def metric_entry(sm: SeasonMetrics, key: str) -> dict[str, Any]:
    m = CATALOGUE[key]
    rel = sm.reliability.get("metrics", {}).get(key) or {}
    out = {"key": key, "label": m.label, "group": m.group, "definition": m.definition, "rule": m.rule,
           "sources": list(m.sources), "unit": m.unit, "kind": m.kind, "per90": m.kind == "per90",
           "ratio": m.kind == "ratio", "higher_is_better": m.higher_is_better, "positions": list(m.positions),
           "digits": m.digits, "noisy": sm.noisy(key), "reliability_r": rel.get("r"),
           "min_minutes": sm.min_minutes, "min_attempts": None, "min_attempts_rule": None,
           "has_percentile": m.kind != "total"}
    if m.kind == "ratio" and m.min_den:
        t = sm.thresholds[m.min_den]
        out["min_attempts"], out["min_attempts_rule"] = t["min"], t["rule"]
    return out


def team_metric_entry(m) -> dict[str, Any]:
    return {"key": m.key, "label": m.label, "definition": m.definition, "rule": m.rule, "sources": list(m.sources),
            "unit": m.unit, "kind": m.kind, "higher_is_better": m.higher_is_better, "digits": m.digits}


# ------------------------------------------------------------------------------------------------ match facts
def read_matches(sm: SeasonMetrics, league: dict, root: Path) -> tuple[dict, dict]:
    """From each fixture's stream (same folder and order as the engine): event clocks for evidence, and every shot."""
    from regista.season.build import materialise

    clock: dict[tuple[str, str], dict] = {}
    shots: dict[str, list[dict]] = {}
    for mi, fx in enumerate(league["fixtures"]):
        assert sm.match_rows[mi]["match_id"] == fx["match_id"], "fixture order differs from the engine's"
        d = materialise(league, fx, root)
        stream = list(iter_jsonl(d / "events.jsonl"))
        header = stream[0]
        g = {p["player_id"]: p.get("global_player_id") for p in header.get("players", [])}
        ltr = {p["period"]: p.get("left_to_right_team_id") for p in header.get("periods", [])}
        home, away = header.get("home_team_id"), header.get("away_team_id")
        for rec in stream:
            if rec.get("type") != "event":
                continue
            c = rec.get("clock") or {}
            clock[(fx["match_id"], rec["id"])] = {"minute": c.get("minute"), "period": c.get("period")}
            if rec["event_type"] != "shot" or not rec.get("player_id"):
                continue
            gid = g.get(rec["player_id"])
            if not gid:
                continue
            period = c.get("period", 1)
            attacker = ltr.get(period) or (home if period % 2 else away)
            pt, end = rec.get("pitch") or {}, rec.get("pitch_end") or {}

            def frame(p: dict) -> tuple[float | None, float | None]:
                if "x" not in p:
                    return None, None
                if attacker == rec["team_id"]:
                    return round(p["x"], 1), round(p["y"], 1)
                return round(PITCH_L - p["x"], 1), round(PITCH_W - p["y"], 1)

            x, y = frame(pt)
            ex, ey = frame(end)
            q = set(rec.get("qualifiers") or [])
            outcome = next((o for o in ("goal", "saved", "blocked", "off_target") if o in q), rec.get("outcome"))
            cid, _owner = sm.clip_index[mi].find(rec["player_id"], rec["id"], rec["t"])
            met = rec.get("metrics") or {}
            shots.setdefault(gid, []).append({
                "match_id": fx["match_id"], "round": fx["round"],
                "opponent": fx["away"] if rec["team_id"] == home else fx["home"],
                "event_id": rec["id"], "t": round(rec["t"], 2), "minute": c.get("minute"), "period": period,
                "x": x, "y": y, "end_x": ex, "end_y": ey, "xg": r(met.get("xg"), 3),
                "distance_m": r(met.get("shot_distance_m"), 1), "outcome": outcome,
                "body_part": rec.get("body_part"), "penalty": "penalty" in q, "under_pressure": bool(rec.get("under_pressure")),
                "clip_id": cid, "video_url": VIDEO_URL.format(match_id=fx["match_id"], clip_id=cid) if cid else None})
    return clock, shots


# ------------------------------------------------------------------------------------------------ players
def player_entry(sm: SeasonMetrics, person: dict, profile: dict | None, clock: dict, shots: dict) -> dict[str, Any]:
    gid = person["global_id"]
    b = league_mod.bio(person)
    out: dict[str, Any] = {
        "id": gid, "name": person["name"], "club_id": person["club_id"], "club": person["club"],
        "short_name": person["short_name"], "position": person["position"], "role": person.get("role"),
        "kit_number": person["kit_number"], "starter": bool(person.get("starter")), **{k: b.get(k) for k in BIO},
        "minutes": 0.0, "appearances": 0, "qualified": False, "metrics": {}, "evidence": {}, "moments": [], "shots": [],
        "heatmap": profile["grid"] if profile else [[0] * GRID_X for _ in range(GRID_Y)], "form": None, "similar": []}
    ps = sm.player(gid)
    if ps is None:
        return out
    card = sm.card(ps)
    out.update(minutes=card["minutes"], appearances=card["appearances"], qualified=card["qualified"])
    opponent_of = {row["match_id"]: row["opponent"] for row in ps.matches}

    moments: list[dict] = []
    index: dict[tuple, int] = {}

    def moment(item: dict) -> int:
        k = (item["match_id"], item.get("event_id"), item.get("t"), item.get("clip_id"))
        if k not in index:
            c = clock.get((item["match_id"], item.get("event_id")), {})
            cid = item.get("clip_id")
            index[k] = len(moments)
            moments.append({"match_id": item["match_id"], "round": item["round"],
                            "opponent": opponent_of.get(item["match_id"]), "t": item.get("t"),
                            "minute": c.get("minute"), "clip_id": cid,
                            "video_url": VIDEO_URL.format(match_id=item["match_id"], clip_id=cid) if cid else None})
        return index[k]

    for key in CATALOGUE:
        cell = sm.cell(ps, key)
        out["metrics"][key] = {k: cell.get(k) for k in ("value", "total", "num", "den", "percentile", "qualified")
                               if k in cell}
        ev = sm.evidence(ps, key, limit=EVIDENCE_CAP)
        if ev["per_match"]:      # physical: one value per match, no clip
            items = [{"match_id": i["match_id"], "round": i["round"], "opponent": opponent_of.get(i["match_id"]),
                      "minutes": i["minutes"], "value": i["value"]} for i in ev["items"]]
            out["evidence"][key] = {"total": ev["total"], "per_match": True, "items": items}
        else:
            items = []
            for i in ev["items"]:
                it: dict[str, Any] = {"m": moment(i), "v": i["value"]}
                if i.get("note"):
                    it["note"] = i["note"]
                items.append(it)
            out["evidence"][key] = {"total": ev["total"], "per_match": False, "items": items}
    out["moments"] = moments
    out["shots"] = shots.get(gid, [])

    keys = list(DEFAULT_COLUMNS.get(person["position"], DEFAULT_COLUMNS[None]))
    f_all = sm.form(ps, list(CATALOGUE))
    out["form"] = {"matches": [{k: row[k] for k in ("match_id", "round", "date", "opponent", "home", "starter", "minutes",
                                                       "score")} for row in f_all["matches"]],
                   "values": {k: v["values"] for k, v in f_all["metrics"].items()},
                   "consistency": {k: {x: f_all["metrics"][k][x] for x in ("mean", "sd", "cv", "matches_counted",
                                                                          "last3_minus_season")} for k in keys}}
    sim = sm.similar(gid, SIMILAR_N)
    out["similar"] = [{"id": s["global_id"], "name": s["name"], "club_id": s["club_id"], "similarity": s["similarity"],
                       "shared_strengths": s["shared_strengths"]} for s in sim["similar"]]
    return out


# ------------------------------------------------------------------------------------------------ teams
def team_entry(sm: SeasonMetrics, cid: str) -> dict[str, Any]:
    ts = sm.team_style(cid)
    sp = []
    for e in ts["evidence"].get("set_piece_xg", []):
        sp.append({"match_id": e["match_id"], "round": e["round"], "event_id": e["event_id"], "t": e["t"],
                   "value": e["value"]})
    return {"club_id": cid, "club": ts["club"], "short_name": ts["short_name"], "matches": ts["matches"],
            "minutes": ts["minutes"], "values": ts["values"],
            "per_match": [{k: pm[k] for k in ("match_id", "round", "opponent", "home", "values")} for pm in ts["per_match"]],
            "evidence": {"set_piece_xg": sp}}


# ------------------------------------------------------------------------------------------------ checks
def hidden_keys_in(obj: Any, path: str = "$") -> list[str]:
    found = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in HIDDEN_KEYS:
                found.append(f"{path}.{k}")
            found += hidden_keys_in(v, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            found += hidden_keys_in(v, f"{path}[{i}]")
    return found


def build(app: str) -> dict[str, Any]:
    league_path = REPO / "data" / "season" / "league.json"
    root = REPO / "data" / "season" / "matches"
    sm = load_metrics(league_path, root)
    season = load_season(league_path, root)
    league = sm.league
    clock, shots = read_matches(sm, league, root)

    clubs = [{"club_id": c["club_id"], "name": c["name"], "short_name": c["short_name"], "ground": c.get("ground"),
              "kit": c["kit"]} for c in league["clubs"]]
    people = sm.people
    players = [player_entry(sm, p, season.player(gid), clock, shots) for gid, p in people.items()]
    sample = sm.sample()
    table = [{k: row[k] for k in ("position", "club_id", "club", "short_name", "played", "won", "drawn", "lost",
                                   "goals_for", "goals_against", "goal_difference", "points")} for row in season.table]
    matches = [{"match_id": m["match_id"], "round": m["round"], "date": m["date"], "home": m["home"], "away": m["away"],
                "score": [m["score"].get("t_home", 0), m["score"].get("t_away", 0)]} for m in sm.match_rows]
    return {
        "generated": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "engine": {"generator": league.get("generator"), "schema": "regista.season.metrics (part A, feature/terminal-engine)",
                   "league": league.get("league"), "season": league.get("season")},
        "app": app,
        "video_url_rule": "a video_url is relative to app: play app + video_url (the local app on part A's code; the live "
                          "app still runs the old league, so never point clips at it)",
        "synthetic": True, "note": SYNTHETIC_NOTE,
        "evidence_rule": f"Evidence lists at most {EVIDENCE_CAP} items per metric per player, in match order (the engine "
                         "API's default); 'total' is the full count. Items point into the player's 'moments' by index "
                         "('m') with the event's value toward the metric ('v': 1 for a count, the xG of a shot, the xT "
                         "added by a move, ...). Physical metrics' evidence is one value per match (no clip).",
        "season": {"min_minutes": sm.min_minutes, "matches_per_club": sm.matches_per_club, "thresholds": sm.thresholds,
                   "sample": sample, "peer_groups": "positions GK, DF, MF, FW",
                   "percentile_rule": "FBref: the mean of the share of peers strictly below and at or below; inverted where "
                                      "lower is better; only qualified players (minutes, and attempts for a ratio) get one",
                   "noise_r": sm.reliability.get("noise_r"),
                   "noisy_rule": "split-half reliability within a role below noise_r: one season cannot yet separate "
                                 "players on this metric (regista.season.reliability)"},
        "groups": GROUPS, "sources": SOURCES,
        "metrics": [metric_entry(sm, k) for k in CATALOGUE],
        "default_columns": {k or "all": list(v) for k, v in DEFAULT_COLUMNS.items()},
        "similarity_template": {k: list(v) for k, v in SIMILARITY_TEMPLATE.items()},
        "team_metrics": [team_metric_entry(m) for m in TEAM_CATALOGUE.values()],
        "clubs": clubs, "matches": matches, "table": table,
        "teams": [team_entry(sm, c["club_id"]) for c in league["clubs"]],
        "pitch": {"length": PITCH_L, "width": PITCH_W, "frame": "attacking left to right (x = length toward the opponent "
                  "goal at x = length)", "heatmap_grid": [GRID_X, GRID_Y],
                  "heatmap_rule": "touch-map events per cell, rows y (0 to width), columns x (0 to length), attacking "
                                  "left to right, the same grid as the profile page"},
        "players": players,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--app", default=DEFAULT_APP, help="the app base that serves clip videos (default %(default)s)")
    ap.add_argument("--out", default=str(SANDBOX / "terminal.json"))
    args = ap.parse_args(argv)
    data = build(args.app)
    leaks = hidden_keys_in(data)
    assert not leaks, f"hidden rating keys reached the export: {leaks[:5]}"
    text = json.dumps(data, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
    # belt and braces: no hidden rating name appears as a JSON key anywhere in the text
    for k in HIDDEN_KEYS:
        assert f'"{k}":' not in text, f"hidden rating key {k!r} in the export text"
    out = Path(args.out)
    out.write_text(text + "\n", encoding="utf-8")
    played = sum(1 for p in data["players"] if p["appearances"])
    print(f"wrote {out} ({out.stat().st_size / 1e6:.2f} MB): {len(data['metrics'])} metrics, {len(data['players'])} "
          f"players ({played} played), {len(data['teams'])} clubs, {len(data['matches'])} matches", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
