def in_box(x: float, y: float) -> bool:
    """Inside the attacking penalty area (attacking frame: the opponent's goal at x = 105)."""
    return x >= BOX_X and BOX_Y0 <= y <= BOX_Y1


def length_band(d: float) -> str | None:
    """FBref's pass lengths: short 5-15 yd, medium 15-30 yd, long over 30 yd (under 5 yd: none)."""
    if d < SHORT_M:
        return None
    if d < MEDIUM_M:
        return "short"
    if d <= LONG_M:
        return "medium"
    return "long"


def third(x: float) -> str:
    return "own_third" if x < OWN_THIRD_X else "mid_third" if x < FINAL_THIRD_X else "final_third"


def spells(stream: list[Record]) -> dict[str, tuple[float, float]]:
    """player id -> (on, off) in video time, for every player who played (``playing_time.played_seconds``'s rule: starters
    from the first period's start, substitutions and red cards start or end a spell)."""
    header = stream[0]
    periods = header.get("periods", [])
    first = periods[0]["t"] if periods else 0.0
    last = periods[-1]["t_end"] if periods else float("inf")
    start = {p["player_id"]: first for p in header.get("players", []) if p.get("starter")}
    end: dict[str, float] = {}
    for e in stream:
        if e.get("type") != "event":
            continue
        if e["event_type"] == "substitution" and e.get("player_id") and e.get("related_player_id"):
            end.setdefault(e["player_id"], e["t"])
            start.setdefault(e["related_player_id"], e["t"])
        elif e["event_type"] == "card_red" and e.get("player_id"):
            end.setdefault(e["player_id"], e["t"])
    return {pid: (t0, end.get(pid, last)) for pid, t0 in start.items()}


@dataclass
class MatchMetrics:
    """One match, by per-match player id: counts (``counts[pid][key]``), the events behind them (``evidence[pid][key]``:
    (event id, t, value, note) tuples), minutes, physical records, team counts, and the moves and shots xT is fitted on."""

    match_id: str
    header: Record
    minutes: dict[str, float] = field(default_factory=dict)
    spells: dict[str, tuple[float, float]] = field(default_factory=dict)
    counts: dict[str, dict[str, float]] = field(default_factory=lambda: defaultdict(lambda: defaultdict(float)))
    evidence: dict[str, dict[str, list[tuple]]] = field(default_factory=lambda: defaultdict(lambda: defaultdict(list)))
    peaks: dict[str, tuple[float, float]] = field(default_factory=dict)   # pid -> (peak km/h, played_s)
    teams: dict[str, dict[str, float]] = field(default_factory=lambda: defaultdict(lambda: defaultdict(float)))
    team_evidence: dict[str, dict[str, list[tuple]]] = field(default_factory=lambda: defaultdict(lambda: defaultdict(list)))
    moves: list[tuple] = field(default_factory=list)    # (pid, event id, t, "pass" | "carry", sx, sy, ex, ey, success)
    shots_xt: list[tuple] = field(default_factory=list)  # (sx, sy, xg), non-penalty shots in the attacking frame
    shot_list: list[Record] = field(default_factory=list)  # every shot (penalties too): where, xG, outcome (the shot map)

    def add(self, pid: str | None, key: str, value: float = 1.0, rec: Record | None = None, note: str | None = None) -> None:
        if not pid:
            return
        self.counts[pid][key] += value
        if rec is not None and key not in HELPERS:
            self.evidence[pid][key].append((rec["id"], rec["t"], value, note))

    def team_add(self, team: str | None, key: str, value: float = 1.0, rec: Record | None = None) -> None:
        if not team:
            return
        self.teams[team][key] += value
        if rec is not None:
            self.team_evidence[team][key].append((rec["id"], rec["t"], value, None))


def analyse_match(stream: list[Record]) -> MatchMetrics:
    """Every player's and team's counts for one match stream (header first, as every Regista stream). Pure: no files, no
    league; the season adds xT and the global ids."""
    header = stream[0]
    mm = MatchMetrics(match_id=header.get("match_id", ""), header=header)
    periods = header.get("periods", [])
    home, away = header.get("home_team_id"), header.get("away_team_id")
    other = {home: away, away: home}
    ltr = {p["period"]: p.get("left_to_right_team_id") for p in periods}
    position = {p["player_id"]: p.get("position") for p in header.get("players", [])}
    team_of = {p["player_id"]: p.get("team_id") for p in header.get("players", [])}
    mm.minutes = {pid: s / 60.0 for pid, s in played_seconds(stream).items()}
    mm.spells = spells(stream)

    def period_at(rec: Record) -> int:
        c = rec.get("clock")
        if c and c.get("period"):
            return c["period"]
        t = rec.get("t", 0.0)
        best = periods[0]["period"] if periods else 1
        for p in periods:
            if t >= p["t"]:
                best = p["period"]
        return best

    def frame(team: str | None, pt: Record | None, period: int) -> tuple[float, float] | None:
        """(x, y) in ``team``'s attacking frame: its opponent's goal at x = 105."""
        if not pt:
            return None
        attacker = ltr.get(period) or (home if period % 2 else away)
        return (pt["x"], pt["y"]) if attacker == team else (PITCH_L - pt["x"], PITCH_W - pt["y"])

    timeline = [r for r in stream if r.get("type") in ("event", "possession")]
    possessions = [r for r in timeline if r["type"] == "possession"]
    poss_by_id = {p["id"]: p for p in possessions}
    poss_starts: dict[str, list[float]] = defaultdict(list)
    poss_of_team: dict[str, list[Record]] = defaultdict(list)
    for p in possessions:
        poss_starts[p["team_id"]].append(p["t"])
        poss_of_team[p["team_id"]].append(p)

    # --- possession time (in play): each possession, plus the flight of a pass to a teammate
    intervals: list[tuple[float, float, str]] = []
    for i, p in enumerate(possessions):
        t0, t1 = p["t"], p.get("t_end", p["t"])
        nxt = possessions[i + 1] if i + 1 < len(possessions) else None
        if nxt and nxt["team_id"] == p["team_id"] and p.get("lost_by") == "pass" and 0 <= nxt["t"] - t1 <= FLIGHT_GAP_S:
            t1 = nxt["t"]
        intervals.append((t0, t1, p["team_id"]))
        mm.team_add(p["team_id"], "possession_s", t1 - t0)
    for pid, (on, off) in mm.spells.items():
        mine = team_of.get(pid)
        opp = sum(max(0.0, min(t1, off) - max(t0, on)) for t0, t1, team in intervals if team != mine)
        mm.add(pid, "opp_possession_s", opp)

    # --- sequences: a team's run of possessions until the opponent has the ball or the game restarts
    seq: list[Record] = []

    def close_sequence() -> None:
        if not seq:
            return
        team = seq[0]["team_id"]
        first_gain = seq[0].get("gained_by")
        p0 = frame(team, seq[0].get("pitch"), period_at(seq[0]))
        p1 = frame(team, seq[-1].get("pitch_end") or seq[-1].get("pitch"), period_at(seq[-1]))
        if first_gain in ("tackle", "interception", "loose_ball") and p0 and p0[0] >= HIGH_TURNOVER_X:
            mm.team_add(team, "high_turnovers", 1, seq[0])
        if first_gain not in ("set_piece", "kickoff") and p0 and p1:
            ids = {p["id"] for p in seq}
            mm.team_add(team, "sequences", 1)
            mm.team_add(team, "sequence_progress_m", p1[0] - p0[0])
            mm.team_add(team, "sequence_s", max(0.0, seq[-1].get("t_end", seq[-1]["t"]) - seq[0]["t"]))
            mm.team_add(team, "sequence_passes", sum(1 for e in timeline if e["type"] == "event"
                                                     and e["event_type"] in ("pass", "cross") and e.get("possession_id") in ids))
        seq.clear()

    for p in possessions:
        if seq and (p["team_id"] != seq[-1]["team_id"] or p.get("gained_by") in ("set_piece", "kickoff")):
            close_sequence()
        seq.append(p)
    close_sequence()

    # --- the main pass over events and possessions, in stream order
    chain: dict[str, deque] = defaultdict(lambda: deque(maxlen=6))   # furthest x of each of the team's last six passes
    last_team: str | None = None
    set_piece_at: dict[str, float | None] = {}
    shots_on_pitch: list[tuple[Record, str]] = []
    goals_on_pitch: list[tuple[Record, str]] = []
    index_of = {id(r): i for i, r in enumerate(timeline)}
    last_shot_penalty = False   # a save belongs to the shot just before it

    for r in timeline:
        if r["type"] == "possession":
            team = r["team_id"]
            if team != last_team or r.get("gained_by") == "kickoff":   # a new sequence, or a new phase after a kick-off
                chain[team].clear()
                if last_team is not None:
                    set_piece_at[last_team] = None
                last_team = team
            if r.get("lost_by") in ("dispossessed", "tackled", "out_of_play"):
                mm.add(r["player_id"], "ball_losses", 1, {"id": r["id"], "t": r.get("t_end", r["t"])}, r["lost_by"])
            continue
        et = r["event_type"]
        pid, team = r.get("player_id"), r.get("team_id")
        q = set(r.get("qualifiers") or [])
        period = period_at(r)
        start = frame(team, r.get("pitch"), period)
        end = frame(team, r.get("pitch_end"), period)
        metrics = r.get("metrics") or {}
        if et in SET_PIECES and team:
            set_piece_at[team] = r["t"]
        if not pid:
            continue

        if et == "shot":
            xg = float(metrics.get("xg") or 0.0)
            goal = "goal" in q
            penalty = "penalty" in q
            last_shot_penalty = penalty
            mm.shot_list.append({"event_id": r["id"], "pid": pid, "team": team, "t": r["t"], "period": period,
                                 "x": None if start is None else round(start[0], 1), "y": None if start is None else round(start[1], 1),
                                 "end_x": None if end is None else round(end[0], 1), "end_y": None if end is None else round(end[1], 1),
                                 "xg": round(xg, 3), "outcome": next((o for o in ("goal", "saved", "blocked", "off_target") if o in q),
                                                                     r.get("outcome")),
                                 "body_part": r.get("body_part"), "penalty": penalty,
                                 "distance_m": None if metrics.get("shot_distance_m") is None else round(float(metrics["shot_distance_m"]), 1)})
            mm.add(pid, "xg", xg, r)
            mm.team_add(team, "xg_for", xg)
            mm.team_add(team, "shots_for", 1)
            shots_on_pitch.append((r, team))
            if penalty:
                mm.add(pid, "penalties_taken", 1, r)
                mm.team_add(team, "penalty_xg", xg)
                if goal:
                    mm.add(pid, "penalty_goals", 1, r)
            else:
                mm.add(pid, "shots", 1, r)
                mm.add(pid, "npxg", xg, r)
                mm.team_add(team, "npxg_for", xg)
                mm.add(pid, "np_goals_minus_xg", (1.0 if goal else 0.0) - xg, r)
                mm.add(pid, "shot_distance_sum", float(metrics.get("shot_distance_m") or 0.0))
                if goal or "saved" in q:
                    mm.add(pid, "shots_on_target", 1, r)
                if start:
                    mm.shots_xt.append((start[0], start[1], xg))
                sp = set_piece_at.get(team)
                if sp is not None and r["t"] - sp <= SET_PIECE_WINDOW_S:
                    mm.team_add(team, "set_piece_xg", xg, r)
                    mm.team_add(team, "set_piece_shots", 1, r)
                _key_pass(mm, r, xg, timeline, index_of, poss_by_id)
            if penalty or xg >= BIG_CHANCE_XG:
                mm.add(pid, "big_chances", 1, r)
            _creating_actions(mm, r, goal, timeline, index_of, poss_by_id)
        elif et == "goal":
            mm.add(pid, "goals", 1, r)
            mm.team_add(team, "goals_for", 1)
            goals_on_pitch.append((r, team))
            if "penalty" not in q:
                mm.add(pid, "np_goals", 1, r)
        elif et in ("pass", "cross"):
            _pass(mm, r, pid, team, start, end, q, metrics, chain, poss_by_id, position.get(pid))
        elif et == "carry":
            _carry(mm, r, pid, start, end, metrics, chain[team])
        elif et == "touch":
            mm.add(pid, "touches", 1, r)
            if start and in_box(*start):
                mm.add(pid, "touches_in_box", 1, r)
        elif et == "take_on":
            mm.add(pid, "take_ons", 1, r)
            if r.get("outcome") == "success":
                mm.add(pid, "take_ons_won", 1, r)
                mm.add(r.get("related_player_id"), "dribbled_past", 1, r)
        elif et == "nutmeg":
            mm.add(pid, "nutmegs", 1, r)
        elif et == "skill_move":
            mm.add(pid, "skill_moves", 1, r)
        elif et == "tackle":
            if r.get("outcome", "success") == "success":
                mm.add(pid, "tackles_won", 1, r)
            _ppda_action(mm, team, start)
        elif et == "interception":
            mm.add(pid, "interceptions", 1, r)
            _ppda_action(mm, team, start)
        elif et == "foul":
            mm.add(pid, "fouls", 1, r)
            _ppda_action(mm, team, start)
        elif et == "recovery":
            mm.add(pid, "recoveries", 1, r)
        elif et == "clearance":
            mm.add(pid, "clearances", 1, r)
        elif et == "block":
            mm.add(pid, "blocks", 1, r)
        elif et == "pressure":
            mm.add(pid, "pressures", 1, r)
            mm.team_add(team, "pressures", 1)
            starts = poss_starts.get(team, [])
            k = bisect_right(starts, r["t"])
            if k < len(starts) and starts[k] - r["t"] <= REGAIN_S and poss_of_team[team][k].get("gained_by") in REGAIN_GAINS:
                mm.add(pid, "pressure_regains", 1, r)
        elif et == "aerial_duel":
            mm.add(pid, "aerial_duels_won", 1, r)
            mm.add(r.get("related_player_id"), "aerial_duels_lost", 1, r)
        elif et == "foul_won":
            mm.add(pid, "fouls_won", 1, r)
            if "penalty_won" in q:
                mm.add(pid, "penalties_won", 1, r)
        elif et == "card_yellow":
            mm.add(pid, "yellow_cards", 1, r)
        elif et == "card_red":
            mm.add(pid, "red_cards", 1, r)
        elif et == "offside":
            mm.add(pid, "offsides", 1, r)
        elif et == "assist":
            mm.add(pid, "assists", 1, r)
        elif et == "save" and not last_shot_penalty:   # penalty saves are penalties_saved, not saves (FBref Save%)
            mm.add(pid, "saves", 1, r)

    # --- on the pitch: goals and xG for and against; keepers' shots faced, goals conceded, clean sheets
    for pid, (on, off) in mm.spells.items():
        mine = team_of.get(pid)
        keeper = position.get(pid) == "GK"
        for shot, team in shots_on_pitch:
            if not on <= shot["t"] <= off:
                continue
            xg = float((shot.get("metrics") or {}).get("xg") or 0.0)
            q = set(shot.get("qualifiers") or [])
            if team == mine:
                mm.add(pid, "onpitch_xg_for", xg, shot)
            else:
                mm.add(pid, "onpitch_xg_against", xg, shot)
                if keeper:
                    if q & {"goal", "saved"} and "penalty" not in q:
                        mm.add(pid, "sot_faced", 1, shot)
                    if "penalty" in q:
                        mm.add(pid, "penalties_faced", 1, shot)
                        if "saved" in q:
                            mm.add(pid, "penalties_saved", 1, shot)
        conceded = 0
        for goal, team in goals_on_pitch:
            if on <= goal["t"] <= off:
                if team == mine:
                    mm.add(pid, "onpitch_goals_for", 1, goal)
                else:
                    mm.add(pid, "onpitch_goals_against", 1, goal)
                    conceded += 1
                    if keeper:
                        mm.add(pid, "goals_conceded", 1, goal)
        if not keeper:
            continue
        for key in ("goals_conceded", "sot_faced", "saves", "full_matches", "clean_sheets"):
            mm.counts[pid][key] += 0.0   # a keeper's zero is a value, not a gap
        if periods and on <= periods[0]["t"] and off >= periods[-1]["t_end"]:
            mm.add(pid, "full_matches", 1)
            if not conceded:
                mm.add(pid, "clean_sheets", 1, {"id": None, "t": periods[-1]["t_end"]}, "no goal conceded")

    # --- physical records (league mode, schema 0.2.0)
    for r in stream:
        if r.get("type") != "physical":
            continue
        pid, m = r["player_id"], r.get("metrics") or {}
        stub = {"id": r["id"], "t": r.get("t", 0.0)}
        for key, src in PHYSICAL_FIELDS.items():
            if src in m:
                mm.add(pid, key, float(m[src]), stub if key not in HELPERS else None)
        mm.add(pid, "played_s", float(r.get("played_s") or 0.0))
        if "peak_speed_kmh" in m:
            mm.peaks[pid] = (float(m["peak_speed_kmh"]), float(r.get("played_s") or 0.0))

    for team in (home, away):
        mm.teams[team]["matches"] += 1
        mm.teams[team]["minutes"] += sum(p["t_end"] - p["t"] for p in periods) / 60.0
    for team in (home, away):
        opp = mm.teams[other[team]]
        mine = mm.teams[team]
        mine["xg_against"] = opp["xg_for"]
        mine["goals_against"] = opp["goals_for"]
        mine["shots_against"] = opp["shots_for"]
        mine["opp_possession_s"] = opp["possession_s"]
        mine["opp_passes"] = opp["passes"]
        mine["opp_final_third_passes"] = opp["final_third_passes"]
        mine["opp_build_up_passes"] = opp["build_up_passes"]
    for pid in list(mm.counts):
        derive(mm.counts[pid])
    return mm


def derive(c: dict[str, float]) -> None:
    """Fill the derived counts (``DERIVED``) of one count table in place."""
    for key, parts in DERIVED.items():
        c[key] = sum(sign * c.get(k, 0.0) for k, sign in parts)


def _ppda_action(mm: MatchMetrics, team: str | None, start: tuple[float, float] | None) -> None:
    """A defensive action in the pressing zone (the opponent's own 60%) counts toward the team's PPDA."""
    if team and start and start[0] >= PPDA_ZONE_X:
        mm.team_add(team, "ppda_actions", 1)


def _pass(mm: MatchMetrics, r: Record, pid: str, team: str, start: tuple[float, float] | None, end: tuple[float, float] | None,
          q: set[str], metrics: Record, chain: dict[str, deque], poss_by_id: dict[str, Record], position: str | None) -> None:
    et = r["event_type"]
    ok = r.get("outcome") == "success"
    if start and end:
        dist = float(metrics.get("pass_distance_m") or detmath.hypot(end[0] - start[0], end[1] - start[1]))
    else:
        dist = float(metrics.get("pass_distance_m") or 0.0)
    possession = poss_by_id.get(r.get("possession_id") or "")
    dead_ball = bool(possession and possession.get("gained_by") == "set_piece")
    recipient = r.get("related_player_id")
    mm.add(pid, "passes", 1, r)
    mm.team_add(team, "passes", 1)
    if dist > LONG_M:
        mm.team_add(team, "long_passes", 1)
    if ok:
        mm.add(pid, "passes_completed", 1, r)
        mm.add(pid, "pass_distance", dist, r)
        mm.add(recipient, "passes_received", 1, r)
    else:
        mm.add(pid, "ball_losses", 1, r, et)
    if et == "cross":
        mm.add(pid, "crosses", 1, r)
        if ok:
            mm.add(pid, "crosses_completed", 1, r)
    if r.get("under_pressure"):
        mm.add(pid, "passes_under_pressure", 1, r)
        if ok:
            mm.add(pid, "passes_under_pressure_completed", 1, r)
    band = length_band(dist)
    if band:
        mm.add(pid, f"{band}_passes", 1, r)
        if ok:
            mm.add(pid, f"{band}_passes_completed", 1, r)
    if position == "GK":
        mm.add(pid, "gk_passes", 1, r)
        if ok:
            mm.add(pid, "gk_passes_completed", 1, r)
        if "goal_kick" not in q:
            mm.add(pid, "gk_open_passes", 1)
            mm.add(pid, "gk_pass_length_sum", dist)
            if dist > LAUNCH_M:
                mm.add(pid, "gk_launches", 1)
    if start:
        zone = third(start[0])
        mm.add(pid, f"{zone}_passes", 1, r)
        if ok:
            mm.add(pid, f"{zone}_passes_completed", 1, r)
        if zone == "final_third":
            mm.team_add(team, "final_third_passes", 1)
        if start[0] < PITCH_L - PPDA_ZONE_X:        # in the passing team's own 60%: what the opponent's PPDA counts
            mm.team_add(team, "build_up_passes", 1)
    if start and end and abs(end[1] - start[1]) > SWITCH_M:
        mm.add(pid, "switches", 1, r)
    if "through_ball" in q and ok:
        mm.add(pid, "through_balls", 1, r)
    if not (ok and start and end):
        return
    mm.add(pid, "progressive_pass_distance", max(0.0, end[0] - start[0]), r)
    team_chain = chain[team]
    ref = max([start[0], *team_chain])
    enters_box = in_box(*end) and not in_box(*start)
    if start[0] >= DEFENDING_40_X and (end[0] - ref >= PROGRESSIVE_M - EPS or enters_box):
        mm.add(pid, "progressive_passes", 1, r)
        mm.add(recipient, "progressive_passes_received", 1, r)
    team_chain.append(max(start[0], end[0]))
    if not dead_ball:
        if start[0] < FINAL_THIRD_X <= end[0]:
            mm.add(pid, "passes_final_third", 1, r)
        if enters_box:
            mm.add(pid, "passes_into_box", 1, r)
            if et == "cross":
                mm.add(pid, "crosses_into_box", 1, r)
    mm.moves.append((pid, r["id"], r["t"], "pass", start[0], start[1], end[0], end[1], True))


def _carry(mm: MatchMetrics, r: Record, pid: str, start: tuple[float, float] | None, end: tuple[float, float] | None,
           metrics: Record, team_chain: deque) -> None:
    mm.add(pid, "carries", 1, r)
    if not (start and end):
        return
    dist = float(metrics.get("carry_distance_m") or detmath.hypot(end[0] - start[0], end[1] - start[1]))
    mm.add(pid, "carry_distance", dist, r)
    mm.add(pid, "progressive_carry_distance", max(0.0, end[0] - start[0]), r)
    ref = max([start[0], *team_chain])
    enters_box = in_box(*end) and not in_box(*start)
    if end[0] >= HALFWAY_X and (end[0] - ref >= PROGRESSIVE_M - EPS or enters_box):
        mm.add(pid, "progressive_carries", 1, r)
    if start[0] < FINAL_THIRD_X <= end[0]:
        mm.add(pid, "carries_final_third", 1, r)
    if enters_box:
        mm.add(pid, "carries_into_box", 1, r)
        mm.add(pid, "touches_in_box", 1, r, "carry into the box")
    if r.get("outcome", "success") == "success":
        mm.moves.append((pid, r["id"], r["t"], "carry", start[0], start[1], end[0], end[1], True))


def _key_pass(mm: MatchMetrics, shot: Record, xg: float, timeline: list[Record], index_of: dict[int, int],
              poss_by_id: dict[str, Record]) -> None:
    """FBref's key pass: the completed pass the shooter received at the start of the possession he shot from. Its passer
    gets the key pass and the shot's xG as xA."""
    possession = poss_by_id.get(shot.get("possession_id") or "")
    if not possession or possession.get("gained_by") != "pass_received":
        return
    i = index_of[id(possession)]
    for j in range(i - 1, -1, -1):
        r = timeline[j]
        if r["type"] == "possession":
            return
        if (r["event_type"] in ("pass", "cross") and r.get("outcome") == "success" and r.get("team_id") == shot["team_id"]
                and r.get("related_player_id") == shot["player_id"]):
            mm.add(r["player_id"], "key_passes", 1, r)
            mm.add(r["player_id"], "xa", xg, r)
            return


SCA_KINDS = {"pass": "pass", "cross": "pass", "take_on": "take-on", "shot": "shot", "foul_won": "foul drawn",
             "tackle": "defensive action", "interception": "defensive action"}


def _creating_actions(mm: MatchMetrics, shot: Record, goal: bool, timeline: list[Record], index_of: dict[int, int],
                      poss_by_id: dict[str, Record]) -> None:
    """FBref's shot- (and goal-) creating actions: the two offensive actions directly before the shot, within the shooting
    team's possession (walking back stops at the opponent's possession or a period start)."""
    team = shot["team_id"]
    found = 0
    for j in range(index_of[id(shot)] - 1, -1, -1):
        r = timeline[j]
        if r["type"] == "possession":
            if r["team_id"] != team:
                return
            continue
        et = r["event_type"]
        if et in ("period_start", "period_end", "kick_off"):
            return
        if r.get("team_id") != team or et not in SCA_KINDS:
            continue
        if et in ("pass", "cross", "take_on") and r.get("outcome") != "success":
            continue
        kind = SCA_KINDS[et]
        if kind == "pass":
            possession = poss_by_id.get(r.get("possession_id") or "")
            kind = "dead-ball pass" if possession and possession.get("gained_by") == "set_piece" else "live-ball pass"
        mm.add(r.get("player_id"), "sca", 1, r, kind)
        if goal:
            mm.add(r.get("player_id"), "gca", 1, r, kind)
        found += 1
        if found == 2:
            return


# ============================================================================ xT

def _cell(x: float, y: float) -> tuple[int, int]:
    return (min(XT_GRID_X - 1, max(0, int(x / PITCH_L * XT_GRID_X))), min(XT_GRID_Y - 1, max(0, int(y / PITCH_W * XT_GRID_Y))))


@dataclass
class XTModel:
    """Karun Singh's expected threat on a 12 x 8 grid (attacking frame): xT(z) = s(z) g(z) + m(z) sum T(z -> z') xT(z'),
    iterated to convergence. s and m are the shares of actions in z that are shots and moves (passes, crosses, carries);
    T counts successful moves from z to z' over all moves from z (failed moves carry the ball nowhere); g is the mean xG of
    the non-penalty shots from z (Regista's xG is the generator's own chance quality, and a season has too few goals per
    zone to use goals)."""

    grid: list[list[float]]           # [y][x]
    iterations: int
    actions: int

    def value(self, x: float, y: float) -> float:
        cx, cy = _cell(x, y)
        return self.grid[cy][cx]

    def added(self, sx: float, sy: float, ex: float, ey: float) -> float:
        return self.value(ex, ey) - self.value(sx, sy)

    def public(self) -> Record:
        return {"grid_x": XT_GRID_X, "grid_y": XT_GRID_Y, "frame": "attacking left to right: the opponent's goal at x = 105",
                "values": [[round(v, 4) for v in row] for row in self.grid], "iterations": self.iterations,
                "actions": self.actions, "rule": "Karun Singh xT", "sources": ["KS-XT"]}


def fit_xt(moves: Iterable[tuple], shots: Iterable[tuple], all_moves: Iterable[tuple] = (), tol: float = 1e-9,
           max_iter: int = 200) -> XTModel:
    """Fit xT. ``moves``: successful (sx, sy, ex, ey); ``all_moves``: every attempted move's start (sx, sy), successful or
    not (defaults to the successful ones); ``shots``: (sx, sy, xg)."""
    n = XT_GRID_X * XT_GRID_Y
    idx = lambda x, y: (lambda c: c[1] * XT_GRID_X + c[0])(_cell(x, y))   # noqa: E731
    shot_n, xg_sum, move_n = [0] * n, [0.0] * n, [0] * n
    trans: list[dict[int, int]] = [defaultdict(int) for _ in range(n)]
    moves = list(moves)
    for sx, sy, xg in shots:
        k = idx(sx, sy)
        shot_n[k] += 1
        xg_sum[k] += xg
    for sx, sy, ex, ey in moves:
        trans[idx(sx, sy)][idx(ex, ey)] += 1
    starts = list(all_moves) or [(m[0], m[1]) for m in moves]
    for sx, sy in starts:
        move_n[idx(sx, sy)] += 1
    total = [shot_n[k] + move_n[k] for k in range(n)]
    s = [shot_n[k] / total[k] if total[k] else 0.0 for k in range(n)]
    m = [move_n[k] / total[k] if total[k] else 0.0 for k in range(n)]
    g = [xg_sum[k] / shot_n[k] if shot_n[k] else 0.0 for k in range(n)]
    T = [{j: c / move_n[k] for j, c in trans[k].items()} if move_n[k] else {} for k in range(n)]
    xt = [0.0] * n
    it = 0
    for it in range(1, max_iter + 1):
        new = [s[k] * g[k] + m[k] * sum(p * xt[j] for j, p in T[k].items()) for k in range(n)]
        delta = max(abs(a - b) for a, b in zip(new, xt))
        xt = new
        if delta < tol:
            break
    grid = [[xt[y * XT_GRID_X + x] for x in range(XT_GRID_X)] for y in range(XT_GRID_Y)]
    return XTModel(grid, it, sum(total))


# ============================================================================ clips (the evidence's moments)

@dataclass
class ClipIndex:
    """Which on-ball clip an event sits in: the player's own first, then anyone's, then the player's clip spanning the time."""

    own: dict[tuple[str, str], str] = field(default_factory=dict)
    anyone: dict[str, tuple[str, str]] = field(default_factory=dict)
    spans: dict[str, list[tuple[float, float, str]]] = field(default_factory=dict)

    @classmethod
    def load(cls, match_dir: Path) -> ClipIndex:
        idx = cls()
        p = Path(match_dir) / "clips.jsonl"
        if not p.exists():
            return idx
        for c in iter_jsonl(p):
            if c.get("type") != "clip" or c.get("reason") != "on_ball_main":
                continue
            for eid in c.get("event_ids", []):
                idx.own.setdefault((c["player_id"], eid), c["id"])
                idx.anyone.setdefault(eid, (c["player_id"], c["id"]))
            idx.spans.setdefault(c["player_id"], []).append((c["t"], c["t_end"], c["id"]))
        for v in idx.spans.values():
            v.sort()
        return idx

    def find(self, pid: str, event_id: str | None, t: float | None) -> tuple[str | None, str | None]:
        """(clip id, the clip's player id) or (None, None)."""
        if event_id and (pid, event_id) in self.own:
            return self.own[(pid, event_id)], pid
        if event_id and event_id in self.anyone:
            owner, cid = self.anyone[event_id]
            return cid, owner
        if t is not None:
            for t0, t1, cid in self.spans.get(pid, []):
                if t0 <= t <= t1:
                    return cid, pid
        return None, None


# ============================================================================ the season

def thresholds(team_minutes: float) -> dict[str, Record]:
    """The ratio minimums for this season: FBref's per-squad-game rules times the club's squad games, counted as its minutes
    / 90 (FBref's squad game lasts 90 minutes; a Regista match lasts 30, so ten matches are about 3.3 squad games), rounded
    up; and Regista's flat minimums where FBref publishes none. The same scaling as the qualifying minutes."""
    games = team_minutes / 90.0
    out = {k: {"min": max(1, math.ceil(rate * games - 1e-9)),
               "rule": f"{why}, times {games:.2f} squad games (club minutes / 90), rounded up"}
           for k, (rate, why) in PER_SQUAD_GAME.items()}
    out |= {k: {"min": n, "rule": why} for k, (n, why) in FLAT_MINIMUMS.items()}
    return out


def qualifying_minutes(team_minutes: float) -> float:
    """FBref's rate-leader minimum is 30 minutes per squad game, a third of each 90-minute match; Regista's matches last
    30 minutes, so a player qualifies with a third of his club's minutes (about 100 of 300)."""
    return round(team_minutes / 3.0, 1)


def rank_value(v: float) -> float:
    """A value as percentiles rank it: rounded to 6 decimals, so the same count over the same minutes ties wherever it was
    summed (the profile and the terminal add minutes in different orders)."""
    return round(v, 6)


def fbref_percentile(values: list[float], v: float) -> float:
    """FBref's percentile rank: the mean of the share of the pool strictly below ``v`` and the share at or below it."""
    n = len(values)
    if not n:
        return float("nan")
    return 50.0 * (bisect_left(values, v) + bisect_right(values, v)) / n


