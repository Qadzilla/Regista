@dataclass(frozen=True)
class Metric:
    """One catalogue entry. ``kind``: ``per90`` (count per 90 minutes), ``ratio`` (``num`` / ``den``, at least ``min_den``
    attempts for a percentile), ``padj`` (per 30 minutes of opponent possession), ``max`` / ``mean`` (of per-match values),
    ``total`` (season total, no percentile). ``higher_is_better`` None marks a style marker: ranked by value, never judged."""

    key: str
    label: str
    group: str
    kind: str
    unit: str
    definition: str
    rule: str
    sources: tuple[str, ...]
    positions: tuple[str, ...] = OUTFIELD
    higher_is_better: bool | None = True
    num: str | None = None
    den: str | None = None
    min_den: str | None = None   # a key of the season's thresholds (``thresholds()``), e.g. "shots"
    scale: float = 1.0           # 100 for percentages
    digits: int = 2
    evidence: tuple[str, ...] = ()   # the count keys whose events back this number (default: itself, or num and den)

    def public(self) -> Record:
        return {"key": self.key, "label": self.label, "group": self.group, "kind": self.kind, "unit": self.unit,
                "definition": self.definition, "rule": self.rule, "sources": list(self.sources),
                "positions": list(self.positions), "higher_is_better": self.higher_is_better,
                "per90": self.kind == "per90", "ratio": self.kind == "ratio",
                "components": [k for k in (self.num, self.den) if k], "evidence_from": list(self.evidence_keys()),
                "digits": self.digits, "realism": realism(self.key)}

    def evidence_keys(self) -> tuple[str, ...]:
        if self.evidence:
            return self.evidence
        if self.kind == "ratio":
            return tuple(k for k in (self.num, self.den) if k and k not in HELPERS)
        return (self.key,)


