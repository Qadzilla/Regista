"""The Scout terminal's metrics engine: the industry's scouting metrics, computed from the Regista League's event streams
and physical records.

Every metric has a catalogue entry (:data:`CATALOGUE`): its key, a plain-English label and definition, whose rule it follows
(FBref, Opta, StatsBomb, Wyscout, Karun Singh's xT, FIFA, or Regista's own when no provider publishes one), the sources
(keys of ``docs/scout-terminal/industry-metrics.md``, with links in :data:`SOURCES`), the unit, how it is shown (per 90,
ratio, possession-adjusted, season peak or mean), whether higher is better, and the positions it matters for.

What is computed, per player per match and per season:

- **values** per 90 minutes on the pitch (``regista.season.playing_time``), ratios with a minimum number of attempts, and
  possession-adjusted counts (per 30 minutes of opponent possession, Wyscout);
- **percentiles** against position peers (the league's GK / DF / MF / FW) who played at least the qualifying minutes
  (:func:`qualifying_minutes`), with FBref's percentile rule;
- **evidence**: the events behind every number (match, time, the clip it sits in when one exists), so the terminal can play
  the moments behind any figure;
- **form** (the per-match values) and **consistency**, **similar players** (cosine on standardised per-90 vectors within the
  position), **team style** per club, and **xT** fitted on the season (a 12 x 8 grid).

The data is synthetic: invented players in an invented league, generated by Regista. Nothing here reads the players'
hidden ratings (``regista.season.league.player_attributes``); only the event streams the generator wrote and the public bio.
League fixtures only: confirmed claims and Player-view uploads (vision streams, a 10-type subset) stay on the profiles.
"""

