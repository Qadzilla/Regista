class SeasonMetrics:
    """The whole season's metrics: build once (``load_metrics``), then query."""

    def __init__(self, league: Record):
        from regista.season.league import bio, club_by_id, people

        self.league = league
        self.clubs = club_by_id(league)
        self.people = people(league)
        self.bio = {gid: bio(p) for gid, p in self.people.items()}
        self.players: dict[str, PlayerSeason] = {}
        self.match_rows: list[Record] = []     # {match_id, round, date, home, away, score, title}
        self.clip_index: list[ClipIndex] = []
        self.match_clock: list[Record] = []     # per match: the header's period table (football minutes of a time)
        self.shots: list[Record] = []           # every league shot, in match and time order (the shot maps and team reels)
        self._shot_at: dict[tuple[str, str], Record] = {}
        self.teams: dict[str, Record] = {}
        self.xt: XTModel | None = None
        self.min_minutes = 0.0
        self.matches_per_club = 0
        self.thresholds: dict[str, Record] = {}
        self.peer_pools: dict[tuple[str, str], list[float]] = {}
        self.min_minutes_floor = 0.0   # from_streams: the qualifying minutes' floor (0: a third of a club's minutes)
        self.min_pool = 2              # from_streams: the smallest percentile pool
        # split-half reliability per metric (regista.season.reliability; load_metrics fills it from reliability.json)
        self.reliability: Record = {"metrics": {}, "stale": "not loaded"}

    # ------------------------------------------------------------------ build
    @classmethod
    def from_streams(cls, league: Record, streams: list[tuple[Record, list[Record], ClipIndex | None]], *,
                     xt: XTModel | None = None, min_minutes_floor: float = 0.0, min_pool: int = 2) -> SeasonMetrics:
        """``streams``: (fixture, event stream, clip index or None) for each league fixture.

        The keyword arguments are for the catalogue's sparse competitions (``regista.catalogue.metrics``); their defaults
        are the Regista League's rules, exactly as before them. ``xt``: a fitted xT grid to value moves with instead of
        fitting one on these streams (3-8 matches cannot fit a 12 x 8 grid: the catalogue uses the league's).
        ``min_minutes_floor``: the qualifying minutes are at least this (a third of a club's minutes, as always, when that
        is more). ``min_pool``: a position's percentile pool needs at least this many qualified players."""
        self = cls(league)
        self.min_minutes_floor = float(min_minutes_floor)
        self.min_pool = int(min_pool)
        analysed: list[tuple[Record, MatchMetrics]] = []
        for fx, stream, clips in streams:
            analysed.append((fx, analyse_match(stream)))
            self.clip_index.append(clips or ClipIndex())
        moves = [(m[4], m[5], m[6], m[7]) for _fx, mm in analysed for m in mm.moves]
        starts = [(m[4], m[5]) for _fx, mm in analysed for m in mm.moves]
        # every attempted move's start (failed passes too) for m(z): failed passes and crosses are in the ball-loss evidence
        for fx, stream, _c in streams:
            starts += _failed_move_starts(stream)
        shots = [s for _fx, mm in analysed for s in mm.shots_xt]
        self.xt = fit_xt(moves, shots, starts) if xt is None else xt
        for _fx, mm in analysed:
            for pid, eid, t, kind, sx, sy, ex, ey, _ok in mm.moves:
                key = "xt_passes" if kind == "pass" else "xt_carries"
                mm.add(pid, key, self.xt.added(sx, sy, ex, ey), {"id": eid, "t": t})
            for pid in mm.counts:
                derive(mm.counts[pid])
        self._aggregate(analysed)
        return self

    def _aggregate(self, analysed: list[tuple[Record, MatchMetrics]]) -> None:
        team_minutes: dict[str, float] = defaultdict(float)
        team_matches: dict[str, int] = defaultdict(int)
        teams: dict[str, Record] = {cid: {"totals": defaultdict(float), "matches": [], "evidence": defaultdict(list)}
                                    for cid in self.clubs}
        for mi, (fx, mm) in enumerate(analysed):
            header = mm.header
            local = {p["player_id"]: p.get("global_player_id") for p in header.get("players", [])}
            club_of_team = {t["team_id"]: t.get("club_id") for t in header.get("teams", [])}
            opponent = {header.get("home_team_id"): fx["away"], header.get("away_team_id"): fx["home"]}
            score = header.get("score", {})
            self.match_rows.append({"match_id": mm.match_id, "round": fx["round"], "date": fx["date"], "home": fx["home"],
                                    "away": fx["away"], "score": score})
            self.match_clock.append({"periods": header.get("periods", [])})
            for s in mm.shot_list:
                cid = club_of_team.get(s["team"])
                gid = local.get(s["pid"])
                clip, _owner = self.clip_index[mi].find(s["pid"], s["event_id"], s["t"])
                shot = {"match_id": mm.match_id, "round": fx["round"], "home": fx["home"], "away": fx["away"],
                        "club_id": cid, "opponent": fx["away"] if cid == fx["home"] else fx["home"],
                        "global_id": gid if gid in self.people else None, "player_id": s["pid"],
                        "event_id": s["event_id"], "t": round(s["t"], 2), "minute": self.minute(mi, s["t"]),
                        "period": s["period"], "x": s["x"], "y": s["y"], "end_x": s["end_x"], "end_y": s["end_y"],
                        "xg": s["xg"], "distance_m": s["distance_m"], "outcome": s["outcome"], "body_part": s["body_part"],
                        "penalty": s["penalty"], "clip_id": clip,
                        "video_url": f"/api/matches/{mm.match_id}/clips/{clip}.mp4" if clip else None}
                self.shots.append(shot)
                self._shot_at[(mm.match_id, s["event_id"])] = shot
            for team, c in mm.teams.items():
                cid = club_of_team.get(team)
                if cid not in teams:
                    continue
                team_minutes[cid] += c["minutes"]
                team_matches[cid] += 1
                for k, v in c.items():
                    teams[cid]["totals"][k] += v
                for k, evs in mm.team_evidence[team].items():
                    teams[cid]["evidence"][k] += [(mi, None, *e) for e in evs]
                teams[cid]["matches"].append({"match_id": mm.match_id, "round": fx["round"], "date": fx["date"],
                                              "opponent": fx["away"] if cid == fx["home"] else fx["home"],
                                              "home": cid == fx["home"], "counts": dict(c)})
            for p in header.get("players", []):
                pid, gid = p["player_id"], local.get(p["player_id"])
                if not gid or gid not in self.people or pid not in mm.minutes:
                    continue
                ps = self.players.get(gid)
                if ps is None:
                    ps = self.players[gid] = PlayerSeason(info=self._info(gid))
                ps.appearances += 1
                ps.minutes += mm.minutes[pid]
                counts = mm.counts.get(pid, {})
                for k, v in counts.items():
                    ps.totals[k] += v
                for k, evs in mm.evidence.get(pid, {}).items():
                    ps.evidence[k] += [(mi, pid, *e) for e in evs]
                peak = mm.peaks.get(pid)
                if peak:
                    ps.peaks.append((mi, peak[0], peak[1]))
                ps.matches.append({"match_idx": mi, "match_id": mm.match_id, "round": fx["round"], "date": fx["date"],
                                   "player_id": pid, "club_id": club_of_team.get(p["team_id"]),
                                   "opponent": opponent.get(p["team_id"]), "home": p["team_id"] == header.get("home_team_id"),
                                   "starter": bool(p.get("starter")), "minutes": round(mm.minutes[pid], 1),
                                   "score": f"{score.get('t_home', 0)}–{score.get('t_away', 0)}",
                                   "counts": dict(counts), "peak": peak[0] if peak else None})
        self.matches_per_club = max(team_matches.values(), default=0)
        self.min_minutes = qualifying_minutes(max(team_minutes.values(), default=0.0))
        if self.min_minutes_floor > self.min_minutes:   # a branch: the league (floor 0) keeps its exact float
            self.min_minutes = self.min_minutes_floor
        self.thresholds = thresholds(max(team_minutes.values(), default=0.0))
        for ps in self.players.values():
            ps.values = {k: self._value(ps, m) for k, m in CATALOGUE.items()}
        self._percentiles()
        for cid, t in teams.items():
            self.teams[cid] = {"totals": dict(t["totals"]), "matches": t["matches"], "evidence": t["evidence"],
                               "values": _team_values(t["totals"])}

    def _info(self, gid: str) -> Record:
        p = self.people[gid]
        return {"global_id": gid, "name": p["name"], "club_id": p["club_id"], "club": p["club"], "short_name": p["short_name"],
                "kit": p["kit"], "kit_number": p["kit_number"], "position": p["position"], "role": p.get("role"),
                **{k: v for k, v in self.bio[gid].items() if k != "date_of_birth"}}

    # ------------------------------------------------------------------ values
    def _value(self, ps: PlayerSeason, m: Metric) -> float | None:
        t = ps.totals
        if m.kind == "per90":
            if m.group == "physical" and not t.get("played_s"):
                return None
            return t.get(m.key, 0.0) * 90.0 / ps.minutes if ps.minutes else None
        if m.kind == "ratio":
            den = t.get(m.den, 0.0)
            return t.get(m.num, 0.0) / den * m.scale if den else None
        if m.kind == "padj":
            opp = t.get("opp_possession_s", 0.0)
            return t.get(m.num or m.key, 0.0) / (opp / 60.0) * 30.0 if opp else None
        if m.kind == "max":
            return max((pk for _mi, pk, _s in ps.peaks), default=None)
        if m.kind == "mean":
            pk = [pk for _mi, pk, s in ps.peaks if s >= PEAK_MIN_PLAYED_S]
            return sum(pk) / len(pk) if pk else None
        if m.kind == "total":
            return t.get(m.key, 0.0)
        raise ValueError(m.kind)

    def qualified(self, ps: PlayerSeason, m: Metric) -> bool:
        """In the percentile pool for ``m``: enough minutes, a value, and enough attempts for a ratio."""
        if ps.minutes < self.min_minutes or ps.values.get(m.key) is None or m.kind == "total":
            return False
        if m.kind == "ratio" and m.min_den:
            return ps.totals.get(m.den, 0.0) >= self.thresholds[m.min_den]["min"]
        return True

    def _percentiles(self) -> None:
        for m in CATALOGUE.values():
            pools: dict[str, list[float]] = defaultdict(list)
            for ps in self.players.values():
                if ps.info["position"] in m.positions and self.qualified(ps, m):
                    pools[ps.info["position"]].append(rank_value(ps.values[m.key]))
            for pos, vals in pools.items():
                vals.sort()
                self.peer_pools[(m.key, pos)] = vals
            for ps in self.players.values():
                pos = ps.info["position"]
                vals = pools.get(pos)
                if not vals or len(vals) < self.min_pool or not self.qualified(ps, m) or pos not in m.positions:
                    ps.percentiles[m.key] = None
                    continue
                pct = fbref_percentile(vals, rank_value(ps.values[m.key]))
                ps.percentiles[m.key] = round(100.0 - pct if m.higher_is_better is False else pct)

    def describe(self, key: str) -> Record:
        """A metric's public description plus its split-half reliability in this league (None when not measured) and, for
        a ratio, the attempts a player needs for a percentile this season (``min_attempts``, with its rule)."""
        m = CATALOGUE[key]
        t = self.thresholds.get(m.min_den) if m.kind == "ratio" and m.min_den else None
        return {**m.public(), "reliability": self.reliability.get("metrics", {}).get(key),
                "min_attempts": t["min"] if t else None, "min_attempts_rule": t["rule"] if t else None}

    def minute(self, mi: int, t: float | None) -> int | None:
        """The football minute (1-based, as Regista's clip labels count it) of a time in match ``mi``: matches last 30
        minutes on a 90-minute clock (the second half starts at 46'), so it cannot be read off ``t``."""
        from regista.clips import match_minute

        periods = self.match_clock[mi]["periods"] if mi < len(self.match_clock) else []
        return None if t is None or not periods else match_minute({"periods": periods}, t)

    def noisy(self, key: str) -> bool:
        """Within a role, is one season's ranking on this metric mostly luck (split-half r below NOISE_R)?"""
        return bool((self.reliability.get("metrics", {}).get(key) or {}).get("noisy"))

    def sample(self) -> Record:
        """How much football the season holds: what every per-90 and percentile here rests on."""
        pool = sorted(ps.minutes for ps in self.players.values() if ps.minutes >= self.min_minutes)
        club = max((t["totals"].get("minutes", 0.0) for t in self.teams.values()), default=0.0)
        median = statistics.median(pool) if pool else 0.0
        return {"matches_per_club": self.matches_per_club, "match_minutes": round(club / self.matches_per_club, 1)
                if self.matches_per_club else None, "club_minutes": round(club, 1),
                "qualifying_minutes": round(self.min_minutes, 1), "qualified_players": len(pool),
                "median_qualified_minutes": round(median, 1), "median_full_matches": round(median / 90.0, 1),
                "note": f"Small sample: a club plays {self.matches_per_club} matches of about "
                        f"{round(club / self.matches_per_club) if self.matches_per_club else 0} minutes, so a qualified "
                        f"player's season is about {round(median)} minutes ({median / 90.0:.1f} full matches). Per-90s "
                        "and percentiles rest on that; a metric marked noisy cannot yet separate players in the same "
                        "role over one season (split-half reliability, regista.season.reliability)."}

    def cell(self, ps: PlayerSeason, key: str) -> Record:
        """One metric for one player: the value people read, the count behind it, the percentile and the peer pool."""
        m = CATALOGUE[key]
        v = ps.values.get(key)
        out: Record = {"value": None if v is None else round(v, m.digits), "percentile": ps.percentiles.get(key),
                       "qualified": self.qualified(ps, m)}
        if m.kind == "ratio":
            out["num"] = round(ps.totals.get(m.num, 0.0), 2)
            out["den"] = round(ps.totals.get(m.den, 0.0), 2)
        elif m.kind in ("per90", "padj", "total"):
            out["total"] = round(ps.totals.get(m.num if m.kind == "padj" else key, 0.0), 3 if m.unit in ("xG", "xT") else 1 if m.unit == "m" else 2)
        if m.kind == "padj":
            out["opponent_possession_min"] = round(ps.totals.get("opp_possession_s", 0.0) / 60.0, 1)
        out["peers"] = len(self.peer_pools.get((key, ps.info["position"]), []))
        out["noisy"] = self.noisy(key)
        return out

    # ------------------------------------------------------------------ evidence
    def evidence(self, ps: PlayerSeason, key: str, limit: int | None = None, offset: int = 0) -> Record:
        """The events behind a metric (``Metric.evidence_keys``), in match order, each with its match, time, football
        minute, value and clip. ``offset`` skips that many items (paging); ``limit`` None gives every item from there, a
        number at most that many (0: none); ``total`` always counts them all, so a reader can page until it has them all."""
        m = CATALOGUE[key]
        keys = m.evidence_keys()
        offset = max(0, int(offset))
        if m.group == "physical":
            items = self._match_evidence(ps, key)
            page = items[offset:] if limit is None else items[offset:offset + limit]
            return {"keys": [key], "total": len(items), "moments": len(items), "offset": offset, "items": page, "per_match": True}
        rows = []
        for k in keys:
            for e in ps.evidence.get(k, []):
                rows.append((k, e))
        rows.sort(key=lambda r: (r[1][0], r[1][3] or 0.0))
        total = len(rows)
        moments = len({self._moment_id(e) for _, e in rows})
        rows = rows[offset:] if limit is None else rows[offset:offset + limit]
        return {"keys": list(keys), "total": total, "moments": moments, "offset": offset,
                "items": [self._evidence_item(k, e) for k, e in rows], "per_match": False}

    def evidence_total(self, ps: PlayerSeason, key: str) -> int:
        """How many moments are behind this number (``evidence``'s ``moments``), without building the items: the distinct
        events behind an event metric, or the matches behind a physical one. A ratio or a sum lists an event once per key
        it counts toward (``total`` counts those rows: a pass and its completion are two), and even one key can list an
        event twice (a pass that leads to two shots is two shot-creating actions); a reader shows each event once, so
        this counts each event once, for one key as for several. The Scout terminal shows it ("play its 124 moments", the
        rows its clips drawer plays) and draws a number with nothing behind it as plain text."""
        m = CATALOGUE[key]
        if m.group == "physical":
            return len(self._match_evidence(ps, key))
        return len({self._moment_id(e) for k in m.evidence_keys() for e in ps.evidence.get(k, [])})

    @staticmethod
    def _moment_id(e: tuple) -> tuple:
        """One event, however many keys list it: its match and event id (or its time, for an event without an id), the
        way a reader merges a ratio's or a sum's rows (by match_id and event_id, else t as the item rounds it)."""
        mi, _pid, eid, t, _value, _note = e
        return (mi, eid) if eid else (mi, None, None if t is None else round(t, 2))

    def _evidence_item(self, key: str, e: tuple) -> Record:
        mi, pid, eid, t, value, note = e
        row = self.match_rows[mi]
        cid, owner = self.clip_index[mi].find(pid, eid, t) if pid else (None, None)
        item: Record = {"metric": key, "match_id": row["match_id"], "round": row["round"], "player_id": pid, "event_id": eid,
                        "t": None if t is None else round(t, 2), "minute": self.minute(mi, t), "value": round(value, 4),
                        "clip_id": cid}
        if note:
            item["note"] = note
        if cid:
            item["clip_player_id"] = owner
            item["video_url"] = f"/api/matches/{row['match_id']}/clips/{cid}.mp4"
            item["link"] = f"/?match={row['match_id']}&player={owner}&clip={cid}"
        elif t is not None:
            item["link"] = f"/?match={row['match_id']}&t={round(t, 1)}"
        return item

    def _match_evidence(self, ps: PlayerSeason, key: str) -> list[Record]:
        """Physical numbers come from one record per match: the evidence is each match's value and time on the pitch."""
        m = CATALOGUE[key]
        out = []
        peaks = {mi: (pk, s) for mi, pk, s in ps.peaks}
        for row in ps.matches:
            mi = row["match_idx"]
            if key in ("peak_speed", "peak_speed_mean"):
                if mi not in peaks:
                    continue
                value = peaks[mi][0]
            else:
                src = m.num if m.kind == "ratio" else key
                if src not in row["counts"]:
                    continue
                value = row["counts"][src]
            out.append({"metric": key, "match_id": row["match_id"], "round": row["round"], "player_id": row["player_id"],
                        "minutes": row["minutes"], "value": round(value, 2), "event_id": None, "t": None, "clip_id": None,
                        "link": f"/?match={row['match_id']}&player={row['player_id']}"})
        return out

    # ------------------------------------------------------------------ queries
    def player(self, gid: str) -> PlayerSeason | None:
        return self.players.get(gid)

    def rows(self, *, position: str | None = None, role: str | None = None, club: str | None = None,
             min_minutes: float | None = None, age_min: int | None = None, age_max: int | None = None,
             foot: str | None = None, q: str | None = None) -> list[PlayerSeason]:
        """Players who played, filtered. ``min_minutes`` None: the qualifying minimum."""
        floor = self.min_minutes if min_minutes is None else min_minutes
        out = []
        for ps in self.players.values():
            i = ps.info
            if ps.minutes < floor or (position and i["position"] != position) or (role and i.get("role") != role):
                continue
            if club and club.lower() not in (i["club_id"].lower(), i["club"].lower(), i["short_name"].lower()):
                continue
            if age_min is not None and (i.get("age") is None or i["age"] < age_min):
                continue
            if age_max is not None and (i.get("age") is None or i["age"] > age_max):
                continue
            if foot and i.get("preferred_foot") != foot:
                continue
            if q and not all(w in i["name"].lower() or w in i["club"].lower() for w in q.lower().split()):
                continue
            out.append(ps)
        return out

    def card(self, ps: PlayerSeason) -> Record:
        return {**ps.info, "minutes": round(ps.minutes, 1), "appearances": ps.appearances,
                "qualified": ps.minutes >= self.min_minutes, "profile_url": f"/players/{ps.info['global_id']}"}

    def sort(self, rows: list[PlayerSeason], key: str, order: str | None = None) -> list[PlayerSeason]:
        """By a metric, best first (or ``order`` "asc" / "desc"); players without a value last."""
        m = CATALOGUE[key]
        desc = (m.higher_is_better is not False) if order is None else order == "desc"
        have = [ps for ps in rows if ps.values.get(key) is not None]
        none = [ps for ps in rows if ps.values.get(key) is None]
        have.sort(key=lambda ps: (-ps.values[key] if desc else ps.values[key], ps.info["name"]))
        return have + sorted(none, key=lambda ps: ps.info["name"])

    def form(self, ps: PlayerSeason, keys: list[str]) -> Record:
        """Per-match values of each metric (per 90 of that match, or the match ratio / peak), and the season's consistency."""
        out: dict[str, Record] = {}
        for key in keys:
            m = CATALOGUE[key]
            per_match = []
            for row in ps.matches:
                per_match.append(_match_value(m, row))
            rates = [v for v, row in zip(per_match, ps.matches) if v is not None and row["minutes"] >= FORM_MIN_MINUTES]
            mean = sum(rates) / len(rates) if rates else None
            sd = math.sqrt(sum((v - mean) * (v - mean) for v in rates) / (len(rates) - 1)) if len(rates) > 1 else None
            last3 = [v for v in per_match[-3:] if v is not None]
            season_v = ps.values.get(key)
            out[key] = {"values": [None if v is None else round(v, m.digits) for v in per_match],
                        "season": None if season_v is None else round(season_v, m.digits),
                        "mean": None if mean is None else round(mean, m.digits), "sd": None if sd is None else round(sd, m.digits),
                        "cv": round(sd / abs(mean), 3) if sd is not None and mean else None,
                        "matches_counted": len(rates),
                        "last3_minus_season": round(sum(last3) / len(last3) - season_v, m.digits)
                        if last3 and season_v is not None else None}
        return {"matches": [{k: row[k] for k in ("match_id", "round", "date", "opponent", "home", "starter", "minutes",
                                                   "score", "player_id")} for row in ps.matches],
                "metrics": out}

    def similar(self, gid: str, n: int = SIMILAR_DEFAULT) -> Record:
        """Cosine similarity on standardised per-90 vectors (FBref's summary template; a keeper template for keepers) among
        qualified players in the same position. Missing ratios count as the peer mean (z = 0)."""
        target = self.players[gid]
        pos = target.info["position"]
        keys = SIMILARITY_TEMPLATE["GK" if pos == "GK" else "outfield"]
        pool = [ps for ps in self.players.values() if ps.info["position"] == pos and ps.minutes >= self.min_minutes]
        if target not in pool:
            pool.append(target)
        stats = {}
        for k in keys:
            vals = [ps.values[k] for ps in pool if ps.values.get(k) is not None]
            mu = sum(vals) / len(vals) if vals else 0.0
            sd = math.sqrt(sum((v - mu) * (v - mu) for v in vals) / len(vals)) if vals else 0.0
            stats[k] = (mu, sd)

        def z(ps: PlayerSeason) -> list[float]:
            out = []
            for k in keys:
                v, (mu, sd) = ps.values.get(k), stats[k]
                out.append(0.0 if v is None or not sd else (v - mu) / sd)
            return out

        tz = z(target)
        norm_t = math.sqrt(sum(a * a for a in tz))
        scored = []
        for ps in pool:
            if ps is target:
                continue
            oz = z(ps)
            norm_o = math.sqrt(sum(b * b for b in oz))
            sim = sum(a * b for a, b in zip(tz, oz)) / (norm_t * norm_o) if norm_t and norm_o else 0.0
            shared = [k for k, a, b in zip(keys, tz, oz) if a > 0.5 and b > 0.5]
            scored.append((sim, ps, shared, oz))
        scored.sort(key=lambda s: (-s[0], s[1].info["name"]))
        return {"global_id": gid, "position": pos, "template": list(keys), "pool": len(pool) - 1,
                "target_qualified": target.minutes >= self.min_minutes,
                "z": {k: round(v, 2) for k, v in zip(keys, tz)},
                "similar": [{**self.card(ps), "similarity": round(sim, 3), "shared_strengths": shared,
                             "z": {k: round(v, 2) for k, v in zip(keys, oz)},
                             "values": {k: self.cell(ps, k)["value"] for k in keys}} for sim, ps, shared, oz in scored[:n]]}

    def team_style(self, club_id: str) -> Record:
        t = self.teams[club_id]
        c = self.clubs[club_id]
        values = {}
        for key, m in TEAM_CATALOGUE.items():
            league = [(cid, tt["values"].get(key)) for cid, tt in self.teams.items() if tt["values"].get(key) is not None]
            v = t["values"].get(key)
            desc = m.higher_is_better is not False
            ranked = sorted(league, key=lambda r: -r[1] if desc else r[1])
            rank = next((i for i, (cid, _v) in enumerate(ranked, start=1) if cid == club_id), None)
            mean = sum(x for _c, x in league) / len(league) if league else None
            values[key] = {"value": None if v is None else round(v, m.digits), "rank": rank, "of": len(league),
                           "league_mean": None if mean is None else round(mean, m.digits),
                           "total": round(t["totals"].get(key, 0.0), 3) if m.kind == "per90" else None}
        per_match = [{"match_id": r["match_id"], "round": r["round"], "date": r["date"], "opponent": r["opponent"],
                      "home": r["home"], "values": {k: None if (v := _team_values(r["counts"]).get(k)) is None
                                                    else round(v, TEAM_CATALOGUE[k].digits) for k in TEAM_CATALOGUE}}
                     for r in t["matches"]]
        sp = [self._team_evidence_item(e, "set_piece_xg") for e in t["evidence"].get("set_piece_xg", [])]
        return {"club_id": club_id, "club": c["name"], "short_name": c["short_name"], "kit": c["kit"],
                "matches": len(t["matches"]), "minutes": round(t["totals"].get("minutes", 0.0), 1), "values": values,
                "per_match": per_match, "evidence": {"set_piece_xg": sp}}

    def _team_evidence_item(self, e: tuple, key: str) -> Record:
        """A team number's event (a set-piece shot), with its minute and, from the season's shots, who took it and its clip."""
        mi, _pid, eid, t, value, _note = e
        row = self.match_rows[mi]
        item: Record = {"metric": key, "match_id": row["match_id"], "round": row["round"], "event_id": eid, "t": round(t, 2),
                        "minute": self.minute(mi, t), "value": round(value, 4), "link": f"/?match={row['match_id']}&t={round(t, 1)}"}
        shot = self._shot_at.get((row["match_id"], eid))
        if shot:
            item |= {"global_id": shot["global_id"], "name": self._name(shot["global_id"]), "xg": shot["xg"],
                     "outcome": shot["outcome"], "clip_id": shot["clip_id"], "video_url": shot["video_url"]}
        return item

    def _name(self, gid: str | None) -> str | None:
        return self.people[gid]["name"] if gid in self.people else None

    def player_shots(self, gid: str) -> list[Record]:
        """Every shot the player took in the league, penalties included, in match and time order."""
        return [self._public_shot(s) for s in self.shots if s["global_id"] == gid]

    def team_shots(self, club_id: str, side: str = "for") -> list[Record]:
        """Every shot by the club (``for``) or by its opponents in its matches (``against``), each with who took it."""
        out = []
        for s in self.shots:
            if club_id not in (s["home"], s["away"]) or (s["club_id"] == club_id) != (side == "for"):
                continue
            out.append(self._public_shot(s))
        return out

    def _public_shot(self, s: Record) -> Record:
        gid = s["global_id"]
        p = self.people.get(gid) or {}
        return {**{k: v for k, v in s.items() if k != "player_id"}, "name": p.get("name"), "short_name": p.get("short_name"),
                "position": p.get("position"), "kit_number": p.get("kit_number")}


def _failed_move_starts(stream: list[Record]) -> list[tuple[float, float]]:
    """The attacking-frame start of every failed pass, cross and carry (move attempts in xT's m(z) and T)."""
    header = stream[0]
    periods = header.get("periods", [])
    ltr = {p["period"]: p.get("left_to_right_team_id") for p in periods}
    home, away = header.get("home_team_id"), header.get("away_team_id")
    out = []
    for r in stream:
        if r.get("type") != "event" or r["event_type"] not in ("pass", "cross", "carry") or r.get("outcome", "success") == "success":
            continue
        pt = r.get("pitch")
        if not pt:
            continue
        period = (r.get("clock") or {}).get("period", 1)
        attacker = ltr.get(period) or (home if period % 2 else away)
        out.append((pt["x"], pt["y"]) if attacker == r.get("team_id") else (PITCH_L - pt["x"], PITCH_W - pt["y"]))
    return out


def _match_value(m: Metric, row: Record) -> float | None:
    """One metric in one match: per 90 of that match's minutes, the match ratio, or the match's peak."""
    c = row["counts"]
    if m.kind in ("per90", "padj"):
        if m.group == "physical" and "played_s" not in c:
            return None
        if m.kind == "padj":
            opp = c.get("opp_possession_s", 0.0)
            return c.get(m.num or m.key, 0.0) / (opp / 60.0) * 30.0 if opp else None
        return c.get(m.key, 0.0) * 90.0 / row["minutes"] if row["minutes"] else None
    if m.kind == "ratio":
        den = c.get(m.den, 0.0)
        return c.get(m.num, 0.0) / den * m.scale if den else None
    if m.kind in ("max", "mean"):
        return row.get("peak")
    return c.get(m.key, 0.0)


def _team_values(t: dict[str, float]) -> dict[str, float | None]:
    """A club's style metrics from its summed counts (a season, or one match)."""
    mins = t.get("minutes", 0.0)
    per90 = lambda k: t.get(k, 0.0) * 90.0 / mins if mins else None   # noqa: E731
    share = lambda a, b: a / (a + b) * 100.0 if (a + b) else None     # noqa: E731
    out: dict[str, float | None] = {
        "possession_pct": share(t.get("possession_s", 0.0), t.get("opp_possession_s", 0.0)),
        "pass_share_pct": share(t.get("passes", 0.0), t.get("opp_passes", 0.0)),
        "field_tilt_pct": share(t.get("final_third_passes", 0.0), t.get("opp_final_third_passes", 0.0)),
        "ppda": t.get("opp_build_up_passes", 0.0) / t["ppda_actions"] if t.get("ppda_actions") else None,
        "direct_speed": t.get("sequence_progress_m", 0.0) / t["sequence_s"] if t.get("sequence_s") else None,
        "passes_per_sequence": t.get("sequence_passes", 0.0) / t["sequences"] if t.get("sequences") else None,
        "long_pass_share": t.get("long_passes", 0.0) / t["passes"] * 100.0 if t.get("passes") else None,
    }
    for key in ("xg_for", "xg_against", "npxg_for", "goals_for", "goals_against", "shots_for", "shots_against",
                "set_piece_xg", "set_piece_shots", "penalty_xg", "high_turnovers", "pressures"):
        out[key] = per90(key)
    return out


def catalogue() -> Record:
    """The public catalogue: every player and team metric with its definition and source."""
    return {"metrics": [m.public() for m in CATALOGUE.values()], "team_metrics": [m.public() for m in TEAM_CATALOGUE.values()],
            "groups": GROUPS, "sources": SOURCES, "positions": list(POSITIONS),
            "default_columns": {k or "all": list(v) for k, v in DEFAULT_COLUMNS.items()},
            "similarity_template": {k: list(v) for k, v in SIMILARITY_TEMPLATE.items()}, "note": SYNTHETIC_NOTE}


# ============================================================================ one season per process

_cache: dict[tuple[str, int, str], SeasonMetrics] = {}
_lock = threading.Lock()


def build_season(league: Record, root: Path | str) -> SeasonMetrics:
    """Materialise every fixture (``regista.season.build``) and compute the season's metrics."""
    from regista.season.build import build_all, materialise

    build_all(league, root)   # a cold folder is generated in parallel first
    streams = []
    for fx in league["fixtures"]:
        d = materialise(league, fx, root)
        streams.append((fx, list(iter_jsonl(d / "events.jsonl")), ClipIndex.load(d)))
    return SeasonMetrics.from_streams(league, streams)


def load_metrics(league_path: Path | str, root: Path | str) -> SeasonMetrics:
    """The season's metrics for this league file and match folder, built once per process (rebuilt when the league file
    changes)."""
    from regista.season.league import load_league

    league_path = Path(league_path)
    key = (str(league_path.resolve()), league_path.stat().st_mtime_ns, str(Path(root).resolve()))
    with _lock:
        hit = _cache.get(key)
        if hit is None:
            league = load_league(league_path)
            hit = build_season(league, root)
            from regista.season.reliability import load as load_reliability

            hit.reliability = load_reliability(league_path, league)
            _cache.clear()
            _cache[key] = hit
        return hit


def invalidate() -> None:
    with _lock:
        _cache.clear()


# ============================================================================ command line

DIAGNOSTICS = ("progressive_passes", "progressive_carries", "key_passes", "sca", "touches_in_box", "passes_final_third",
               "passes_into_box", "switches", "through_balls", "pressures", "pressure_regains", "ball_losses", "big_chances",
               "xt_added")


def league_diagnostics(sm: SeasonMetrics) -> Record:
    """League-wide rates per team per 90 (no band: industry-metrics.md cites no Premier League norm for these), ratios,
    and team style ranges. For checking the generator, not for scouting."""
    match_minutes = sum(r["minutes"] for t in sm.teams.values() for r in [t["totals"]]) / 2.0
    tot: dict[str, float] = defaultdict(float)
    for ps in sm.players.values():
        for k, v in ps.totals.items():
            tot[k] += v
    per_team = {k: round(tot[k] / match_minutes * 90.0 / 2.0, 2) for k in DIAGNOSTICS} if match_minutes else {}
    style = {k: [round(t["values"][k], 2) for t in sm.teams.values() if t["values"].get(k) is not None]
             for k in ("possession_pct", "field_tilt_pct", "ppda", "direct_speed", "passes_per_sequence")}
    return {"match_minutes": round(match_minutes, 1), "per_team_per90": per_team,
            "key_passes_per_np_shot": round(tot["key_passes"] / tot["shots"], 3) if tot["shots"] else None,
            "sca_per_shot": round(tot["sca"] / (tot["shots"] + tot["penalties_taken"]), 3) if tot["shots"] else None,
            "pressure_regain_rate": round(tot["pressure_regains"] / tot["pressures"], 3) if tot["pressures"] else None,
            "save_rate": round(tot["saves"] / tot["sot_faced"], 3) if tot["sot_faced"] else None,
            "xt_share_carries": round(tot["xt_carries"] / tot["xt_added"], 3) if tot["xt_added"] else None,
            "team_style_ranges": {k: [min(v), max(v)] if v else None for k, v in style.items()},
            "min_minutes": sm.min_minutes, "qualified_players": sum(ps.minutes >= sm.min_minutes for ps in sm.players.values())}


def main(argv: list[str] | None = None) -> int:
    import argparse
    import json

    ap = argparse.ArgumentParser(prog="python -m regista.season.metrics", description="The Scout terminal's metrics on the league.")
    ap.add_argument("--league", default="data/season/league.json")
    ap.add_argument("--root", default="data/season/matches")
    ap.add_argument("--player", help="a global id: print every metric for this player")
    ap.add_argument("--rank", help="a metric key: print its leaderboard")
    ap.add_argument("--position", choices=POSITIONS)
    args = ap.parse_args(argv)
    sm = load_metrics(args.league, args.root)
    if args.player:
        ps = sm.player(args.player)
        if ps is None:
            ap.error(f"no player {args.player!r} has played")
        print(f"{ps.info['name']} ({ps.info['position']}, {ps.info['club']}), {ps.minutes:.0f} min. {SYNTHETIC_NOTE}")
        for k, m in CATALOGUE.items():
            c = sm.cell(ps, k)
            if c["value"] is not None:
                print(f"  {m.label:<44} {c['value']:>9} {m.unit:<10} pct {c['percentile']}")
    elif args.rank:
        if args.rank not in CATALOGUE:
            ap.error(f"unknown metric {args.rank!r}")
        m = CATALOGUE[args.rank]
        rows = [ps for ps in sm.sort(sm.rows(position=args.position), args.rank) if sm.qualified(ps, m)]
        print(f"{m.label} ({m.rule}): {m.definition}")
        for i, ps in enumerate(rows[:20], start=1):
            print(f"  {i:>2}. {ps.info['name']:<24} {ps.info['short_name']} {ps.info['position']} {sm.cell(ps, args.rank)['value']}")
    else:
        print(json.dumps(league_diagnostics(sm), indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
