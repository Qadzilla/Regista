"""CLI: run Regista's agent pipeline over a match directory.

    python -m regista.agents data/synthetic/sample/syn_0294 --player t_home_09 --query "find me Castellanos doing a nutmeg"
    python -m regista.agents data/synthetic/sample/syn_0294 --player t_home_09 --review     # asks you about unsure clips
    python -m regista.agents data/synthetic/sample/syn_0294 --cloud                         # Foundry + Cosmos DB agents
    python -m regista.agents --graph docs/workflow.md                                       # the workflow diagram

The default engine is the Microsoft Agent Framework workflow (``regista.agents.workflow``). ``--engine orchestrator``
runs the original hand-written orchestrator, kept as a reference implementation.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from regista.agents.orchestrator import Orchestrator
from regista.agents.roles import default_agents


def terminal_reviewer(annotator: str):
    """Ask the person at the terminal about each flagged clip."""
    from regista.agents.workflow import ReviewVerdicts

    def ask(request) -> ReviewVerdicts:
        print(f"\n{request.question}  (k = keep, d = drop, a number 0-1 = keep with that score, Enter = keep)")
        verdicts = []
        for item in request.items:
            mins = f"{int(item['t'] // 60)}:{int(item['t'] % 60):02d}-{int(item['t_end'] // 60)}:{int(item['t_end'] % 60):02d}"
            print(f"\n  {item['title']}\n    {mins}  {item['cut'].replace('_', ' ')}  tags: {', '.join(item['tags'])}")
            print(f"    model {item['watchability']:.2f}" + (f", rules {item['prior_watchability']:.2f}" if item.get("prior_watchability") is not None else "")
                  + f"  - asking because {item['reason']}")
            while True:
                raw = input("    verdict> ").strip().lower()
                if raw in ("", "k", "keep"):
                    verdicts.append({"clip_id": item["clip_id"], "verdict": "keep"})
                    break
                if raw in ("d", "drop"):
                    verdicts.append({"clip_id": item["clip_id"], "verdict": "drop"})
                    break
                try:
                    score = float(raw)
                    if 0.0 <= score <= 1.0:
                        verdicts.append({"clip_id": item["clip_id"], "verdict": "fix", "watchability": score})
                        break
                except ValueError:
                    pass
                print("    please type k, d, or a number between 0 and 1")
        return ReviewVerdicts(verdicts=verdicts, annotator=annotator)

    return ask


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run Regista's agent pipeline.")
    parser.add_argument("match_dir", type=Path, nargs="?")
    parser.add_argument("--player", action="append", default=[], help="player_id (repeatable); default: the player in manifest.json or t_home_09")
    parser.add_argument("--query", action="append", default=[], help="question for the Librarian (repeatable)")
    parser.add_argument("--state-dir", type=Path, default=None, help="where trace.jsonl, dead_letter.jsonl, state.json go (default: <match_dir>/agents)")
    parser.add_argument("--max-retries", type=int, default=2)
    parser.add_argument("--cloud", action="store_true", help="use Foundry (Label, Librarian) and Cosmos DB (Persist) agents from .env / environment")
    parser.add_argument("--engine", choices=["workflow", "orchestrator"], default="workflow")
    parser.add_argument("--review", action="store_true", help="pause and ask you about clips the Label agent is unsure about (workflow engine)")
    parser.add_argument("--annotator", default="zaid", help="name recorded on your verdicts")
    parser.add_argument("--graph", type=Path, nargs="?", const=Path("-"), help="print (or write to a file) the workflow diagram and exit")
    args = parser.parse_args(argv)

    if args.graph is not None:
        from regista.agents.workflow import WorkflowPipeline

        mermaid = WorkflowPipeline(state_dir=Path("/tmp/regista_graph")).mermaid()
        if str(args.graph) == "-":
            print(mermaid)
        else:
            args.graph.parent.mkdir(parents=True, exist_ok=True)
            args.graph.write_text("# Regista agent workflow (Microsoft Agent Framework)\n\nGenerated by `python -m regista.agents --graph docs/workflow.md`.\n\n"
                                  "```mermaid\n" + mermaid + "\n```\n", encoding="utf-8")
            print(f"wrote {args.graph}")
        return 0
    if args.match_dir is None:
        parser.error("match_dir is required unless --graph is given")

    players = args.player
    if not players:
        manifest = args.match_dir / "manifest.json"
        players = [json.loads(manifest.read_text()).get("clips_for") or "t_home_09"] if manifest.exists() else ["t_home_09"]
    if args.cloud:
        from regista.cloud import CloudConfig, agents_for

        from regista.cloud.telemetry import configure_tracing

        config = CloudConfig.from_env()
        agents = agents_for(config, require=True)
        traced = configure_tracing()
        print(f"cloud: {config.describe()}; Foundry tracing: {'on' if traced else 'off'}")
    else:
        agents = default_agents()
    state_dir = args.state_dir or args.match_dir / "agents"
    initial = {"match_dir": str(args.match_dir), "player_ids": players, "queries": args.query, "review": args.review, "annotator": args.annotator}

    if args.engine == "workflow":
        from regista.agents.workflow import WorkflowPipeline

        pipeline = WorkflowPipeline(agents, state_dir, max_retries=args.max_retries, checkpoint_dir=state_dir / "checkpoints")
        result = pipeline.run(initial, reviewer=terminal_reviewer(args.annotator) if args.review else None)
        print(f"engine: Microsoft Agent Framework workflow '{pipeline.workflow.name}'")
    else:
        if args.review:
            parser.error("--review needs the workflow engine")
        result = Orchestrator(agents, state_dir, max_retries=args.max_retries).run(initial)
        print("engine: reference orchestrator")

    for row in result.trace:
        extra = f"  {row['error']}" if row["error"] else (f"  {row['note']}" if row.get("note") else "")
        print(f"{row['agent']:<11} attempt {row['attempt']}  {row['status']:<8} {row['elapsed_ms'] or 0:>8} ms{extra}")
    for pid, clips in result.state.get("clips", {}).items():
        flagged = sum(1 for lb in result.state.get("labels", {}).get(pid, []) if lb.get("review"))
        print(f"{pid}: {len(clips)} clips" + (f", {flagged} still flagged for review" if flagged else ""))
    log = result.state.get("review_log")
    if log:
        print(f"review: {len(log['applied'])} verdict(s) by {log['annotator']} recorded; model: {log['retrained']}")
    for q, ans in zip(args.query, result.state.get("answers", [])):
        print(f"Q: {q}\n   {ans.get('answer') or ans['message']}" + (f"   [{ans['answered_by']}]" if ans.get("answered_by") else ""))
        if ans.get("tools_used"):
            print(f"   tools used: {', '.join(ans['tools_used'])}")
        for r in ans["results"][:5]:
            print(f"   {r['clip_id']}  {r['watchability']:.2f}  {r['title']}")
    print(f"trace: {result.state_dir / 'trace.jsonl'}   dead letters: {len(result.dead_letters)}   ok: {result.ok}")
    if args.cloud:
        from regista.cloud.telemetry import flush_tracing

        flush_tracing()
    return 0 if result.ok else 1


if __name__ == "__main__":
    sys.exit(main())
