def test_words_people_read(page, script, view):
    # Labels come from the API's stat_labels; no raw keys or "per90" reach the page.
    assert "stat_labels" in view
    text = re.sub(r"<[^>]+>", " ", page)
    assert "per90" not in text and "_" not in text
    for js in (script, view):
        for shown in re.findall(r"`([^`]*)`", js):
            visible = re.sub(r"\$\{[^}]*\}|<[^>]+>", " ", shown)
            assert "per90" not in visible, shown
    assert "Higher than ${p}% of the league's" in view  # numbers say what they were measured against


def test_text_from_the_api_is_escaped(script, view):
    # Every innerHTML assignment builds from esc()'d values; titles and names also go through textContent.
    assert "const { esc, api, ApiError } = R;" in script and "const { esc, tagLabel, reasonLabel, fmtTime } = R;" in view
    for js in (script, view):
        for raw in ("${m.title}", "${p.name}", "${P.name}", "${src.title}", "${text}", "${x.text}", "${m.opponent}", "${p.club}"):
            assert raw not in js, raw
    # vsLine(), short(), roundName(), pctText() return plain text: inside markup they are always escaped.
    markup = [line for line in view.splitlines() if "<" in line and ".textContent" not in line]
    assert not [line for line in markup if re.search(r"\$\{(vsLine|short|roundName|pctText|label|tagLabel|reasonLabel)\(", line)]
    assert "${esc(where)}" in view  # the evidence line is built as text, then escaped
    assert "${esc(vsLine(" in view and "${esc(short(" in view and "${esc(roundName(" in view


def test_no_style_attributes_in_markup(page, script, view):
    # The CSP rule of the pages: widths and colours are set on elements after drawing, never as style="" in markup.
    for text in (page, script, view, (PLAYER / "add-match.js").read_text()):
        assert 'style="' not in text and "style=\\\"" not in text and "cssText" not in text
    assert "x.style.width = " in view and "data-w=" in view


def test_the_scripts_parse():
    node = shutil.which("node")
    if node is None:
        pytest.skip("node is not installed")
    for js in ("player.js", "profile-view.js", "add-match.js"):
        res = subprocess.run([node, "--check", str(PLAYER / js)], capture_output=True, text=True, timeout=30)
        assert res.returncode == 0, js + res.stderr


